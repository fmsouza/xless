@Test func xcodebuildHasNoSandboxOfItsOwnAndXlesssAssetTools() {
    let url = URL(fileURLWithPath: "/w/ios/App.xcworkspace"), tools = URL(fileURLWithPath: "/w/.xless/bin")
    func arguments(_ destination: BuildRequest.Destination) -> [String] {
        XcodeBuild.arguments(workspace: url, scheme: "App", configuration: "Release", destination: destination, derivedData: URL(fileURLWithPath: "/w/dd"),
                             xcconfig: URL(fileURLWithPath: "/w/x.xcconfig"), tools: tools, settings: ["DEVELOPMENT_TEAM": "ABCDE12345", "CODE_SIGNING_ALLOWED": "NO"])
    }
    let device = arguments(.iphoneos), words = device.joined(separator: " ")
    #expect(words.hasPrefix("-workspace /w/ios/App.xcworkspace -scheme App -configuration Release -destination generic/platform=iOS -derivedDataPath /w/dd -xcconfig /w/x.xcconfig "))
    for word in ["CODE_SIGNING_ALLOWED=NO", "DEVELOPMENT_TEAM=ABCDE12345", "ENABLE_USER_SCRIPT_SANDBOXING=NO", "OTHER_SWIFT_FLAGS=$(inherited) -disable-sandbox",
                 "ASSETCATALOG_EXEC=/w/.xless/bin/actool", "IBC_EXEC=/w/.xless/bin/ibtool", "-IDEPackageSupportDisableManifestSandbox=1", "-IDEPackageSupportDisablePluginExecutionSandbox=1"] {
        #expect(device.contains(word), "\(word)")
    }
    #expect(arguments(.iphonesimulator).contains("generic/platform=iOS Simulator"))
    #expect(!words.contains("-sdk ") && !words.contains("allowProvisioning"))
}

@Test func aPhasesXcrunFindsXlesssAssetToolsAndXcodesOthers() throws {
    let root = try temporary(), work = root.appendingPathComponent("work")
    defer { try? FileManager.default.removeItem(at: root) }
    let build = xcode(root)
    try ExecutableFile.write("#!/bin/sh\necho \"$XLESS_TOOLCHAIN_META: $*\"\n", to: build.executable, stage: .build)
    try build.writeTools(work: work)
    let bin = work.path + "/.xless/bin"
    func run(_ words: String...) throws -> String { try Shell.run("\(bin)/\(words[0])", Array(words.dropFirst()), stage: .build).stdout.trimmingCharacters(in: .newlines) }
    for tool in ["actool", "ibtool"] {
        #expect(try run(tool, "--version", "a b") == "\(bin)/toolchain-meta.json: shim \(tool) --version a b")
        #expect(try run("xcrun", tool, "--version") == "\(bin)/toolchain-meta.json: shim \(tool) --version")
        #expect(try run("xcrun", "--find", tool) == "\(bin)/\(tool)")
    }
    #expect(try ToolchainMeta.load(from: URL(fileURLWithPath: "\(bin)/toolchain-meta.json")) == build.meta)
    #expect(FileManager.default.isExecutableFile(atPath: "\(bin)/swift"))
}

@Test func aFailedXcodebuildIsReportedByItsErrors() throws {
    let root = try temporary(), log = root.appendingPathComponent("log")
    defer { try? FileManager.default.removeItem(at: root) }
    let build = xcode(root), program = build.sdk.bundle.appendingPathComponent("Developer/usr/bin/xcodebuild")
    try FileManager.default.createDirectory(at: program.deletingLastPathComponent(), withIntermediateDirectories: true)
    try ExecutableFile.write("""
        #!/bin/sh
        echo "$#: $1 $2"
        echo '2026-11-25 xcodebuild[1] connection: <OS_xpc_error: <dictionary>>' >&2
        echo '/w/a.swift:1:1: error: cannot find it'
        echo '/w/a.swift:1:1: error: cannot find it'
        exit 65
        """, to: program, stage: .build)
    let error = #expect(throws: XlessError.self) { try build.run(["-scheme", "A $(B)"], log: log, env: [:], baseEnvironment: ["PATH": "/usr/bin:/bin"]) }
    #expect(error?.cause == "xcodebuild failed: /w/a.swift:1:1: error: cannot find it" && error?.fix.contains(log.path) == true)
    #expect(try String(contentsOf: log, encoding: .utf8).hasPrefix("2: -scheme A $(B)\n"))
    try ExecutableFile.write("#!/bin/sh\necho nothing to do\n", to: program, stage: .build)
    try build.run([], log: log, env: [:], baseEnvironment: ["PATH": "/usr/bin:/bin"])
    #expect(try String(contentsOf: log, encoding: .utf8) == "nothing to do\n")
}

