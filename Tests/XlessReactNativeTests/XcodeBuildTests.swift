@Test func onAMacTheSimulatorsAppIsSignedFromTheInsideOut() throws {
    let root = try temporary(), app = root.appendingPathComponent("A.app"), ext = app.appendingPathComponent("PlugIns/E.appex")
    defer { try? FileManager.default.removeItem(at: root) }
    for (bundle, name, id) in [(app, "A", "com.example.a"), (ext, "E", "com.example.a.e")] {
        try FileManager.default.createDirectory(at: bundle, withIntermediateDirectories: true)
        try FileManager.default.copyItem(atPath: "/usr/bin/true", toPath: bundle.appendingPathComponent(name).path)
        try Plist.write(["CFBundleExecutable": name, "CFBundleIdentifier": id], to: bundle.appendingPathComponent("Info.plist"), stage: .build)
    }
    let library = app.appendingPathComponent("Frameworks/libl.dylib")
    try FileManager.default.createDirectory(at: library.deletingLastPathComponent(), withIntermediateDirectories: true)
    try FileManager.default.copyItem(atPath: "/usr/bin/true", toPath: library.path)
    try SimulatorBuild.signAdHocOnAMac(app, nested: ["PlugIns/E.appex"], scratch: root, baseEnvironment: ["PATH": "/usr/bin:/bin"])
    try Shell.run("/usr/bin/codesign", ["--verify", "--deep", "--strict", app.path], stage: .build)
    for (code, id) in [(app, "com.example.a"), (ext, "com.example.a.e"), (library, "libl")] {
        let about = try Shell.run("/bin/sh", ["-c", "/usr/bin/codesign -dv \"$1\" 2>&1", "sh", code.path], stage: .build).stdout
        #expect(about.contains("Signature=adhoc") && about.contains("Identifier=\(id)"), "\(about)")
    }
}
