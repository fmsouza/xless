    let text = try XcodeBuild.configuration([("My App", "My App", ["PRODUCT_BUNDLE_IDENTIFIER": "com.example.app", "MARKETING_VERSION": "1.2"]),
                                             ("My App", "1-Share", ["PRODUCT_BUNDLE_IDENTIFIER": "com.example.app.share"])])
