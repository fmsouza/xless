    XLESS_MARKETING_VERSION__My_App__My_App = 1.2
    XLESS_PRODUCT_BUNDLE_IDENTIFIER__My_App__My_App = com.example.app
    XLESS_PRODUCT_BUNDLE_IDENTIFIER__My_App____Share = com.example.app.share
    MARKETING_VERSION = $(XLESS_MARKETING_VERSION__$(PROJECT_NAME:c99extidentifier)__$(TARGET_NAME:c99extidentifier):default=$(inherited))
    PRODUCT_BUNDLE_IDENTIFIER = $(XLESS_PRODUCT_BUNDLE_IDENTIFIER__$(PROJECT_NAME:c99extidentifier)__$(TARGET_NAME:c99extidentifier):default=$(inherited))

    """)
}

