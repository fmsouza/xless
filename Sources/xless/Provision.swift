// `xless provision plan|apply`: everything the project needs from the account, declared by xless.yml (or the overlay)
// and appstore/, planned in dependency order and applied in one process (docs/apple-account.md#xless-provision).
// Nothing is ever deleted or revoked: what differs that way is reported as drift with the command that would fix it.

enum ProvisionArea: String, Encodable, CaseIterable, Sendable {
    case bundleIDs = "bundle-ids", capabilities, appGroups = "app-groups", iCloudContainers = "icloud-containers", certificates, keys,
         profiles, app, listing, privacy, testflight

    var title: String {
        switch self {
        case .bundleIDs: "Bundle IDs"
        case .capabilities: "Capabilities"
        case .appGroups: "App groups"
        case .iCloudContainers: "iCloud containers"
        case .certificates: "Certificates"
        case .keys: "Keys"
        case .profiles: "Profiles"
        case .app: "App record"
        case .listing: "App Store listing"
        case .privacy: "App Privacy"
        case .testflight: "TestFlight"
        }
    }
}

/// One thing `apply` does.
struct ProvisionStep: Sendable {
    enum Action: String, Encodable, Sendable { case create, enable, update, assign, push }

    /// Where a certificate's private key comes from.
    enum KeySource: Sendable, Equatable {
        /// Generated by xless and stored first, as this entry.
        case generate(entry: String)
        /// The store's key, whose certificate is gone.
        case stored(entry: String)
        /// The key in this environment variable (or its `_FILE`).
        case environment(String)
    }

    enum Work: @unchecked Sendable {
        case bundleID(String)
        case capability(String, CapabilityRequest)
        case linked(PortalLinkedKind, String, bundles: [String])
        case certificate(CertificateKind, KeySource)
        case apnsKey
        case profile(SigningTarget)
        case app(AppCreateRequest)
        case listing
        case privacy(AppYAML.Privacy)
        case betaGroup(String, external: Bool)
    }

    var area: ProvisionArea
    var action: Action
    var subject: String
    var details: [String] = []
    /// Done through the Apple ID web session.
    var web = false
    /// false: whether anything is needed is known only once the web session reads it (`apply` checks; nothing is sent
    /// when it is in place).
    var checked = true
    var work: Work

    /// Whether applying it writes the secret store (a new key, or a certificate ID recorded with a stored key).
    var writesStore: Bool {
        switch work {
        case .certificate(_, .generate), .certificate(_, .stored), .apnsKey: true
        default: false
        }
    }

    var text: String {
        let sign = switch action { case .create: "+"; case .enable: "+"; case .update: "~"; case .assign: "~"; case .push: "~" }
        let marks = (web ? " [web]" : "") + (checked ? "" : " (checked when applied)")
        // The listing's details are the changes of a push, some of several lines; every other one is a line.
        let lines = if case .listing = work { true } else { false }
        return (["  \(sign) \(action.rawValue) \(TerminalText.escaped(subject))\(marks)"] + details.map { "      \(TerminalText.escaped($0, keepingLines: lines))" }).joined(separator: "\n")
    }
}

extension ProvisionStep: Encodable {
    enum CodingKeys: String, CodingKey { case area, action, subject, details, webSession, checked }
    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(area, forKey: .area); try c.encode(action, forKey: .action); try c.encode(subject, forKey: .subject)
        try c.encode(details, forKey: .details); try c.encode(web, forKey: .webSession); try c.encode(checked, forKey: .checked)
    }
}

/// Something that differs and that `provision` leaves alone (it would delete, revoke or replace), with the fix.
struct ProvisionDrift: Encodable, Sendable, Equatable {
    var area: ProvisionArea
    var subject: String
    var message: String
    var fix: String
}

/// Something that stops `apply` before anything is sent.
struct ProvisionBlocker: Error, Encodable, Sendable, Equatable {
    var area: ProvisionArea
    var message: String
    var fix: String
}

/// What the account already has that later steps need: resource IDs found while planning, or made while applying.
struct ProvisionState: Sendable, Equatable {
    var bundles: [String: String] = [:]
    var certificates: [CertificateKind: String] = [:]
    var appID: String?
    /// The secrets the listing's push would send, by name.
    var listingSecrets: [String] = []
}

struct ProvisionPlan: Sendable {
    var team: String
    var steps: [ProvisionStep] = []
    var drift: [ProvisionDrift] = []
    var blockers: [ProvisionBlocker] = []
    var notes: [String] = []
    var known = ProvisionState()

    var webSteps: Int { steps.filter(\.web).count }

    /// Refuses a plan with blockers: nothing is sent.
    func requireUnblocked() throws {
        guard let first = blockers.first else { return }
        throw XlessError(.account, "\(first.message); nothing was sent" + (blockers.count > 1 ? " (and \(blockers.count - 1) more: see `xless provision plan`)" : ""), fix: first.fix).printable
    }

    mutating func add(_ area: ProvisionArea, _ action: ProvisionStep.Action, _ subject: String, _ details: [String] = [], web: Bool = false,
                      checked: Bool = true, _ work: ProvisionStep.Work) {
        steps.append(ProvisionStep(area: area, action: action, subject: subject, details: details, web: web, checked: checked, work: work))
    }

    /// The plan grouped by area, then the drift, the blockers and the notes. What in their names (the project's, Apple's)
    /// would drive the terminal or start a line of its own is written out (`TerminalText`).
    var text: String {
        var out = ""
        for area in ProvisionArea.allCases {
            let steps = self.steps.filter { $0.area == area }
            guard !steps.isEmpty else { continue }
            out += "\(area.title):\n" + steps.map { $0.text + "\n" }.joined()
        }
        out += Self.driftText(drift, heading: "Drift")
        if !blockers.isEmpty {
            out += "Blocked (nothing is applied until these are fixed):\n"
            out += blockers.map { "  x \(TerminalText.escaped("\($0.message) — \($0.fix)"))\n" }.joined()
        }
        out += notes.map { "note: \(TerminalText.escaped($0))\n" }.joined()
        return out + summary + "\n"
    }

    /// The drift section of the plan (and of what `apply` found while applying), empty without drift.
    static func driftText(_ drift: [ProvisionDrift], heading: String) -> String {
        guard !drift.isEmpty else { return "" }
        return "\(heading) (left as it is: provision never deletes, revokes or replaces):\n" + drift.map { "  ! \(TerminalText.escaped("\($0.subject): \($0.message) — \($0.fix)"))\n" }.joined()
    }

    var summary: String {
        guard !steps.isEmpty else { return "nothing to do: the account has what team \(team)'s project needs" }
        let web = webSteps
        return "\(steps.count) step\(steps.count == 1 ? "" : "s") to apply" + (web == 0 ? "" : " (\(web) through the Apple ID web session)")
    }
}

extension ProvisionPlan: Encodable {
    enum CodingKeys: String, CodingKey { case team, steps, drift, blockers, notes }
    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(team, forKey: .team); try c.encode(steps, forKey: .steps); try c.encode(drift, forKey: .drift)
        try c.encode(blockers, forKey: .blockers); try c.encode(notes, forKey: .notes)
    }
}

/// The `appstore/` manifest, read and checked: the listing to push, or why it cannot be.
struct ProvisionStore: Sendable {
    var manifest: StoreManifest
    var listing: any ProvisionListing
}

// MARK: - Plan

/// Reads the account and lists what `apply` would do, in dependency order: bundle IDs, capabilities, app groups and
/// iCloud containers, certificates, the APNs key, profiles, the app record, the listing, App Privacy, TestFlight groups.
struct ProvisionPlanner {
    let inputs: ProvisionInputs
    let account: any ProvisionAccount
    /// The kept Apple ID session, when there is one: planning never signs in.
    let web: ProvisionWebSide?
    let vault: ProvisionVault
    /// nil without `appstore/`.
    var store: ProvisionStore?
    /// Why `appstore/` cannot be pushed (its errors), when it cannot.
    var storeBlocker: ProvisionBlocker?
    var companyName: String?
    var now = Date()

    /// Capabilities Apple enables on every new bundle ID: never reported as drift.
    static let enabledByApple: Set<CapabilityType> = [.inAppPurchase, .gameCenter]
    static let noWebSession = "checked when applied: reading it needs the Apple ID web session (keep one with `xless auth login --keep` to plan it exactly)"

    var team: String { inputs.team }

    func plan() async throws -> ProvisionPlan {
        var plan = ProvisionPlan(team: team)
        plan.notes = inputs.notes
        try await planBundleIDs(&plan)
        try await planCapabilities(&plan)
        for kind in PortalLinkedKind.allCases { try await planLinked(kind, &plan) }
        try await planCertificates(&plan)
        try await planAPNsKey(&plan)
        try await planProfiles(&plan)
        try await planApp(&plan)
        try await planListing(&plan)
        try await planPrivacy(&plan)
        try await planTestFlight(&plan)
        try blockUnwritableStore(&plan)
        return plan
    }

    /// A store this xless must not rewrite (a newer xless wrote it) blocks the plan when a step would write it: apply
    /// refuses before anything is sent, instead of making a key or certificate at Apple it cannot keep or record.
    func blockUnwritableStore(_ plan: inout ProvisionPlan) throws {
        guard let step = plan.steps.first(where: \.writesStore), let file = try vault.file() else { return }
        do { try file.requireWritable() } catch {
            let e = XlessError.wrapping(error, stage: .account)
            plan.blockers.append(ProvisionBlocker(area: step.area, message: "\(step.area.title), \(step.action.rawValue) \(step.subject) writes the secret store, and \(e.cause)",
                                                  fix: e.fix))
        }
    }

    func planBundleIDs(_ plan: inout ProvisionPlan) async throws {
        for id in inputs.bundleIDs {
            if let resource = try await account.bundleID(id) { plan.known.bundles[id] = resource; continue }
            plan.add(.bundleIDs, .create, id, ["registered as universal (iOS and macOS), named \"\(PortalName.bundleID(for: id))\""], .bundleID(id))
        }
    }

    /// The capabilities a bundle's entitlements need, over every platform it is signed for (first settings win).
    func requests(for id: String) -> (requests: [CapabilityRequest], unmapped: [String]) {
        var requests: [CapabilityRequest] = []
        var unmapped: [String] = []
        for t in inputs.targets where t.bundleID == id {
            let needs = Capabilities.required(entitlements: t.entitlements, platform: t.platform)
            for r in needs.requests where !requests.contains(where: { $0.type == r.type }) { requests.append(r) }
            for k in needs.unmapped where !unmapped.contains(k) { unmapped.append(k) }
        }
        return (requests, unmapped)
    }

    func planCapabilities(_ plan: inout ProvisionPlan) async throws {
        for id in inputs.bundleIDs {
            let (requests, unmapped) = self.requests(for: id)
            for key in unmapped {
                plan.notes.append("\(id): the App Store Connect API has no capability for the entitlement \(key): enable it at https://developer.apple.com/account/resources/identifiers/list (the sign stage checks the profile carries it)")
            }
            var existing: [SigningCapability] = []
            if let resource = plan.known.bundles[id] { existing = try await account.capabilities(of: resource) }
            for r in requests {
                let settings = r.settings.map { s in "\(s.key): \(CapabilitySetting.chosen([s]).values.first ?? "")" }
                guard let have = existing.first(where: { $0.type == r.type.rawValue }) else {
                    plan.add(.capabilities, .enable, "\(r.type.rawValue) (\(r.type.displayName)) on \(id)", settings, .capability(id, r))
                    continue
                }
                // Only a setting the entitlements name (the Data Protection level) is managed; others stay as enabled.
                if r.type == .dataProtection, !CapabilitySetting.chosen(r.settings).allSatisfy({ have.settings[$0.key] == $0.value }) {
                    plan.add(.capabilities, .update, "\(r.type.rawValue) (\(r.type.displayName)) on \(id)",
                             settings.map { "\($0) (now \(have.settings.values.sorted().joined(separator: ", ")))" }, .capability(id, r))
                }
            }
            // A bundle whose entitlements are not known (a React Native app before its first build) has no drift to report.
            guard inputs.targets.allSatisfy({ $0.bundleID != id || $0.entitlementsKnown }) else { continue }
            let gated = Set(inputs.targets.filter { $0.bundleID == id }.flatMap { Capabilities.map(for: $0.platform).values })
            for c in existing {
                guard let type = CapabilityType(rawValue: c.type), gated.contains(type), !Self.enabledByApple.contains(type),
                      !requests.contains(where: { $0.type == type }) else { continue }
                plan.drift.append(ProvisionDrift(area: .capabilities, subject: "\(c.type) on \(id)", message: "enabled, and no entitlement of \(id) needs it",
                                                 fix: "`xless bundle-ids capabilities \(id) disable \(c.type)` once no app uses it"))
            }
        }
    }

    /// The `group.…` / `iCloud.…` identifiers the targets' entitlements name, with the bundles using each, in order.
    func linkedUses(_ kind: PortalLinkedKind) -> [(identifier: String, bundles: [String])] {
        let keys = kind == .appGroup ? ["com.apple.security.application-groups"]
            : ["com.apple.developer.icloud-container-identifiers", "com.apple.developer.ubiquity-container-identifiers"]
        var out: [(identifier: String, bundles: [String])] = []
        for t in inputs.targets {
            for key in keys {
                for value in Self.strings(t.entitlements[key]) where value.hasPrefix(kind.prefix) {
                    if let i = out.firstIndex(where: { $0.identifier == value }) {
                        if !out[i].bundles.contains(t.bundleID) { out[i].bundles.append(t.bundleID) }
                    } else { out.append((value, [t.bundleID])) }
                }
            }
        }
        return out
    }

    static func strings(_ v: Any?) -> [String] {
        if let s = v as? String { return [s] }
        return (v as? [Any])?.compactMap { $0 as? String } ?? []
    }

    func planLinked(_ kind: PortalLinkedKind, _ plan: inout ProvisionPlan) async throws {
        let uses = linkedUses(kind)
        guard !uses.isEmpty else { return }
        let area: ProvisionArea = kind == .appGroup ? .appGroups : .iCloudContainers
        guard let web else {
            for use in uses {
                plan.add(area, .assign, use.identifier, ["created if the team has none, assigned to \(use.bundles.joined(separator: ", "))", Self.noWebSession],
                         web: true, checked: false, .linked(kind, use.identifier, bundles: use.bundles))
            }
            return
        }
        let portal = web.portal(kind)
        let all = try await portal.list()
        var states: [String: (PortalBundleID, LinkedState)] = [:]
        for b in Set(uses.flatMap(\.bundles)).sorted() where plan.known.bundles[b] != nil {
            let bundle = try await portal.bundle(b)
            states[b] = (bundle, try await portal.linked(of: bundle))
        }
        for use in uses {
            let item = all.first { $0.identifier == use.identifier }
            var details: [String] = []
            if item == nil { details.append("created, named \"\(PortalName.from(identifier: use.identifier))\"") }
            let missing = use.bundles.filter { b in
                guard let item, let state = states[b]?.1 else { return true }
                return !state.enabled || !state.ids.contains(item.id)
            }
            if !missing.isEmpty { details.append("assigned to \(missing.joined(separator: ", "))") }
            guard !details.isEmpty else { continue }
            plan.add(area, item == nil ? .create : .assign, use.identifier, details, web: true, .linked(kind, use.identifier, bundles: use.bundles))
        }
        for (b, (_, state)) in states.sorted(by: { $0.key < $1.key }) where inputs.targets.allSatisfy({ $0.bundleID != b || $0.entitlementsKnown }) {
            let wanted = Set(uses.filter { $0.bundles.contains(b) }.map(\.identifier))
            for id in state.ids {
                let identifier = all.first { $0.id == id }?.identifier ?? id
                guard !wanted.contains(identifier) else { continue }
                plan.drift.append(ProvisionDrift(area: area, subject: "\(identifier) on \(b)", message: "assigned, and no entitlement of \(b) names it",
                                                 fix: "`xless \(kind.command) unassign \(b) \(identifier)` once no app uses it"))
            }
        }
    }

    func planCertificates(_ plan: inout ProvisionPlan) async throws {
        let file = try vault.file()
        for kind in inputs.certificateKinds {
            let valid = try await account.list(types: kind.types, withContent: true).filter { ($0.expires ?? .distantFuture) > now }
            let name = kind.certificateType.displayName
            func matching(_ pem: String) -> ASCCertificate? {
                guard let key = try? SigningKey(pem: pem) else { return nil }
                return key.certificate(in: valid, now: now).valid?.certificate
            }
            func found(_ cert: ASCCertificate, from source: String) {
                plan.known.certificates[kind] = cert.id
                if let expires = cert.expires, expires < now.addingTimeInterval(30 * 86_400) {
                    plan.notes.append("the \(name) certificate \(cert.id) (\(source)) expires on \(CertTable.day(expires)): create the next one before then (docs/account.md#rotate-a-certificate)")
                }
            }
            if let pem = try vault.environmentKey(kind.secretName) {
                if let cert = matching(pem) { found(cert, from: "the key in \(kind.secretName)"); continue }
                plan.add(.certificates, .create, name, ["for the private key in \(kind.secretName) (the environment), which no valid certificate matches"],
                         .certificate(kind, .environment(kind.secretName)))
                continue
            }
            let entry: VaultEntry?
            do { entry = try file.flatMap { try VaultResolver.preferredCandidate(for: kind.secretName, in: $0, team: team) } } catch {
                let e = XlessError.wrapping(error, stage: .account)
                plan.blockers.append(ProvisionBlocker(area: .certificates, message: e.cause, fix: e.fix))
                continue
            }
            if let entry, let file {
                if let id = entry.metadata.certificateID, let cert = valid.first(where: { $0.id == id }) { found(cert, from: entry.name); continue }
                // No recorded certificate, or one that is gone: a certificate made for the key since (an earlier apply that
                // could not record it) is found by its public key, and never made twice.
                let secret = try vault.open(entry, in: file, reason: "matching \(entry.name) with its certificate")
                defer { secret.wipe() }
                if let cert = matching(secret.utf8String()) { found(cert, from: entry.name); continue }
                plan.add(.certificates, .create, name, ["for the private key stored as \(entry.name), whose certificate is gone (revoked or expired); recorded with it"],
                         .certificate(kind, .stored(entry: entry.name)))
                continue
            }
            guard file != nil else {
                plan.blockers.append(ProvisionBlocker(area: .certificates, message: "no \(name) key is stored, and the secret store that would keep a new one is not set up",
                                                      fix: "`xless secrets init`, then plan again (or give the key in \(kind.secretName)_FILE)"))
                continue
            }
            let entryName = CertificateKeyStore.entryName(base: kind.secretName, team: team)
            var details = ["a new private key, generated and stored as \(entryName) before the request is sent"]
            if !valid.isEmpty { details.append("the team has \(valid.count) other \(name) certificate\(valid.count == 1 ? "" : "s"), whose private keys xless does not have") }
            plan.add(.certificates, .create, name, details, .certificate(kind, .generate(entry: entryName)))
        }
    }

    static let apsKeys = ["aps-environment", "com.apple.developer.aps-environment"]

    /// Whether this machine has an APNs key of the team: in the environment (`XLESS_APNS_KEY`, `_FILE`), or in the store
    /// (an auth key recording the apns service, or any entry named `XLESS_APNS_KEY…` of the team, however it was imported).
    func hasAPNsKey(_ file: SecretCatalog?) throws -> Bool {
        let base = AuthKeyStore.base(for: [.apns])
        if try vault.environmentKey(base) != nil { return true }
        return (file?.entries ?? []).contains { e in
            let teams = e.metadata.teamID == team || e.name.hasSuffix("@\(team)") || (e.metadata.teamID == nil && !e.name.contains("@"))
            return teams && ((e.kind == .authKey && AuthKeyStore.services(of: e).contains(.apns)) || e.name.hasPrefix(base))
        }
    }

    /// The team's APNs keys at Apple (the web session), or nil when they cannot be read without signing in.
    static func apnsKeysAtApple(_ web: ProvisionWebSide?) async throws -> [PortalAuthKey]? {
        guard let web else { return nil }
        return try await web.authKeys.list().filter { $0.serviceKinds.contains(.apns) }
    }

    func planAPNsKey(_ plan: inout ProvisionPlan) async throws {
        guard inputs.targets.contains(where: { t in Self.apsKeys.contains { t.entitlements[$0] != nil } }) else { return }
        let file = try vault.file()
        guard try !hasAPNsKey(file) else { return }
        // One APNs key serves every app of the team, and Apple allows two: one the team has elsewhere is not made again.
        if let existing = try await Self.apnsKeysAtApple(web), let key = existing.first {
            plan.notes.append(Self.apnsElsewhere(key))
            return
        }
        guard file != nil else {
            plan.notes.append("the app uses push notifications and no APNs key is on this machine; the secret store that would keep a new one is not set up (`xless secrets init`, then plan again), or give your push server's key to it with `xless secrets import`")
            return
        }
        plan.add(.keys, .create, "APNs key", ["the app's entitlements use push notifications (aps-environment), and neither the secret store nor the environment has an APNs key of team \(team)",
                                              "unless the team has one already (checked when applied); stored as \(AuthKeyStore.base(for: [.apns]))…@\(team): Apple offers its private key once"],
                 web: true, checked: web != nil, .apnsKey)
    }

    static func apnsElsewhere(_ key: PortalAuthKey) -> String {
        "the team already has APNs key \(key.id) (\"\(key.name)\"), which is not on this machine: xless does not make another (one serves every app of the team); if you have its .p8, `xless secrets import XLESS_APNS_KEY --file AuthKey_\(key.id).p8 --kind auth-key`"
    }

    func planProfiles(_ plan: inout ProvisionPlan) async throws {
        for t in inputs.targets {
            let type = t.profileType
            let name = t.profileName
            let cert = plan.known.certificates[t.signingKind]
            let details = ["\(type.displayName) for \(t.label), with the \(t.signingKind.certificateType.displayName) certificate\(cert.map { " \($0)" } ?? (plan.steps.contains { $0.area == .certificates && $0.subject == t.signingKind.certificateType.displayName } ? " created above" : ""))"]
            guard let bundle = plan.known.bundles[t.bundleID] else { plan.add(.profiles, .create, name, details, .profile(t)); continue }
            let profiles = try await account.profiles(named: name, type: type)
            guard !profiles.isEmpty else { plan.add(.profiles, .create, name, details, .profile(t)); continue }
            let problems: [[String]] = profiles.map { t.problems(of: $0, bundle: bundle, certificate: cert, now: now) }
            guard !problems.contains(where: { $0.isEmpty }), let first = profiles.first else { continue }
            plan.drift.append(ProvisionDrift(area: .profiles, subject: "\(name) (\(first.id))", message: problems[0].joined(separator: "; "),
                                             fix: "`xless profiles renew \(first.id)` (or let `xless sign` replace it)"))
        }
    }

    func planApp(_ plan: inout ProvisionPlan) async throws {
        guard let bundle = inputs.appStoreBundleID, storeBlocker == nil else { return }
        if let manifestBundle = store?.manifest.app.bundleID, manifestBundle != bundle {
            plan.blockers.append(ProvisionBlocker(area: .app, message: "appstore/app.yml is for \(manifestBundle), and the project's App Store app is \(bundle)",
                                                  fix: "set app.yml's bundleID to \(bundle), or point --dir at that app's manifest"))
            return
        }
        if let app = try await account.findApp(bundleID: bundle) { plan.known.appID = app.id; return }
        guard let manifest = store?.manifest else {
            plan.notes.append("\(bundle) has no app record, and there is no appstore/ to take its name and primary locale from: the app record, the listing, App Privacy and TestFlight are left out (`xless store validate` checks a new appstore/; `xless apps create` makes the record by hand)")
            return
        }
        let locale = manifest.app.primaryLocale
        guard let locale, let rawName = manifest.locales[locale]?.name else {
            plan.blockers.append(ProvisionBlocker(area: .app, message: "\(bundle) has no app record, and xless takes its name and primary locale from appstore/",
                                                  fix: "add appstore/app.yml (primaryLocale) and appstore/<locale>/name.txt, or create it with `xless apps create --bundle-id \(bundle) …`"))
            return
        }
        let request: AppCreateRequest
        do {
            request = AppCreateRequest(name: try AppName.validate(rawName), bundleID: bundle, sku: try AppSKU.validate(manifest.app.sku ?? bundle),
                                       primaryLocale: try AppLocale.normalize(locale), platforms: inputs.appPlatforms(for: bundle),
                                       versionString: manifest.app.version ?? inputs.version, companyName: companyName)
        } catch let e as IdentifierInputError {
            plan.blockers.append(ProvisionBlocker(area: .app, message: "\(bundle) has no app record, and appstore/ cannot create one: \(e.description)", fix: "fix appstore/, then plan again"))
            return
        }
        plan.add(.app, .create, "app record for \(bundle)",
                 ["\"\(request.name)\", SKU \(request.sku), primary locale \(request.primaryLocale), \(request.platforms.joined(separator: " and ")) version \(request.versionString)"],
                 web: true, .app(request))
    }

    func planListing(_ plan: inout ProvisionPlan) async throws {
        guard inputs.appStoreBundleID != nil else { return }
        if let storeBlocker { plan.blockers.append(storeBlocker); return }
        guard let store else { return }
        guard let appID = plan.known.appID else {
            plan.add(.listing, .push, "appstore/", ["planned once the app record exists: text, review details, declarations, price and availability, screenshots and previews"], .listing)
            // A new version's review details: the demo account's password goes with them.
            if let demo = store.manifest.app.review?.demoAccount, let name = demo.passwordSecret, demo.required == true || demo.name != nil { plan.known.listingSecrets = [name] }
            return
        }
        let listing: ProvisionListingPlan
        do { listing = try await store.listing.plan(appID: appID) } catch {
            let e = XlessError.wrapping(error, stage: .account)
            plan.blockers.append(ProvisionBlocker(area: .listing, message: e.cause, fix: e.fix))
            return
        }
        plan.notes += listing.notes
        plan.drift += listing.held.map(Self.listingDrift)
        if !listing.changes.isEmpty {
            plan.add(.listing, .push, "appstore/", listing.changes, .listing)
            plan.known.listingSecrets = listing.secrets
        }
    }

    /// Something of the listing `store push` would delete or replace: provision leaves it.
    static func listingDrift(_ subject: String) -> ProvisionDrift {
        ProvisionDrift(area: .listing, subject: subject, message: "the manifest would delete or replace it", fix: "`xless store push` (it asks before deleting)")
    }

    func planPrivacy(_ plan: inout ProvisionPlan) async throws {
        guard let bundle = inputs.appStoreBundleID, let want = store?.manifest.app.privacy, storeBlocker == nil else { return }
        guard let web, let appID = plan.known.appID else {
            plan.add(.privacy, .push, "app.yml privacy", [web == nil ? Self.noWebSession : "sent once the app record exists"], web: true, checked: web != nil, .privacy(want))
            return
        }
        let split: (send: [StoreChange], held: [StoreChange])
        do { split = Self.privacyChanges(try await web.privacy.plan(want, app: appID, appName: bundle)) } catch {
            let e = XlessError.wrapping(error, stage: .account)
            plan.blockers.append(ProvisionBlocker(area: .privacy, message: e.cause, fix: e.fix))
            return
        }
        for change in split.held {
            plan.drift.append(ProvisionDrift(area: .privacy, subject: change.subject, message: "app.yml no longer declares it, and removing it would delete answers",
                                             fix: "`xless store privacy push` (it shows what it removes)"))
        }
        if !split.send.isEmpty { plan.add(.privacy, .push, "app.yml privacy", split.send.map(\.text), web: true, .privacy(want)) }
    }

    /// App Privacy changes that only add or change answers, and those that remove a whole declaration (held: provision
    /// never deletes). Publishing goes with what is sent, never alone after held removals.
    static func privacyChanges(_ changes: [StoreChange]) -> (send: [StoreChange], held: [StoreChange]) {
        let held = changes.filter { $0.action == .delete }
        var send = changes.filter { $0.action != .delete }
        if !held.isEmpty, send.allSatisfy({ $0.privacy == [.publish] }) { send = [] }
        return (send, held)
    }

    func planTestFlight(_ plan: inout ProvisionPlan) async throws {
        guard inputs.appStoreBundleID != nil, let tf = inputs.testflight, plan.known.appID != nil || store != nil else { return }
        let wanted = tf.groups.map { ($0, false) } + (tf.external?.groups ?? []).map { ($0, true) }
        var existing: [ProvisionGroup] = []
        if let appID = plan.known.appID { existing = try await account.betaGroups(app: appID) }
        for (name, external) in wanted {
            if let found = existing.first(where: { $0.name == name }) {
                if found.isInternal == external {
                    plan.blockers.append(ProvisionBlocker(area: .testflight, message: "the TestFlight group \(name) exists as an \(found.isInternal ? "internal" : "external") group",
                                                          fix: "move it to testflight.\(found.isInternal ? "groups" : "external.groups") in the config, or rename it"))
                }
                continue
            }
            plan.add(.testflight, .create, "group \(name)", [external ? "external: testers get a build once beta app review approves it" : "internal, with every build (automatic distribution)"],
                     .betaGroup(name, external: external))
        }
    }
}

// MARK: - Apply

/// What one applied step did.
struct ProvisionDone: Encodable, Sendable, Equatable {
    var area: ProvisionArea
    var subject: String
    var result: String
}

/// What `apply` did: the steps done, and the drift found while applying (the listing, planned again once a new App
/// Store version or the app record exists, may hold things the manifest would delete or replace).
struct ProvisionApplied: Sendable, Equatable {
    var done: [ProvisionDone] = []
    var drift: [ProvisionDrift] = []
}

/// `apply` stopped: blocked before anything was sent (`failed` nil), or at a step. `error` is what the command reports
/// and exits with; `applied` and `left` (the steps not attempted) go into `--json`.
struct ProvisionApplyFailure: Error, StageReportableError {
    struct Failed: Encodable, Sendable, Equatable {
        var area: ProvisionArea
        var action: ProvisionStep.Action
        var subject: String
        var cause: String
        var fix: String
    }

    var applied: ProvisionApplied
    var failed: Failed?
    var left: [ProvisionStep]
    var error: XlessError

    func stageError(_ stage: Stage) -> XlessError { error }
}

/// Runs a plan's steps in order. Each step reads again what it changes (a step already done meanwhile sends nothing),
/// so a failed apply is re-run safely; the first failure stops it with what was done and what is left.
struct ProvisionApplier {
    let inputs: ProvisionInputs
    let account: any ProvisionAccount
    /// Signs in (or restores the kept session), when a step needs it.
    let web: () async throws -> ProvisionWebSide
    let vault: ProvisionVault
    var store: ProvisionStore?
    var say: (String) -> Void = { _ in }
    var now = Date()

    var team: String { inputs.team }

    /// One line, whatever the names in it (the project's, Apple's).
    func tell(_ line: String) { say(TerminalText.escaped(line)) }

    func apply(_ plan: ProvisionPlan) async throws -> ProvisionApplied {
        do { try plan.requireUnblocked() } catch {
            throw ProvisionApplyFailure(applied: ProvisionApplied(), failed: nil, left: plan.steps, error: XlessError.wrapping(error, stage: .account))
        }
        var state = plan.known
        var side: ProvisionWebSide?
        var applied = ProvisionApplied()
        /// Step `i` stopped the apply.
        func failure(at i: Int, _ error: any Error) -> ProvisionApplyFailure {
            let step = plan.steps[i], e = XlessError.wrapping(error, stage: .account)
            let done = applied.done
            let left = plan.steps[done.count...].map { "\($0.area.title): \($0.action.rawValue) \($0.subject)" }
            tell("done: " + (done.isEmpty ? "nothing" : done.map(\.result).joined(separator: "; ")))
            tell("left: " + left.joined(separator: "; "))
            let failure = XlessError(.account, "\(step.area.title), \(step.action.rawValue) \(step.subject): \(e.cause) (\(done.count) of \(plan.steps.count) steps were done, \(left.count) left)",
                                     fix: "\(e.fix); then re-run `xless provision apply`: it plans again and does only what is left").printable
            return ProvisionApplyFailure(applied: applied, failed: .init(area: step.area, action: step.action, subject: step.subject, cause: e.cause, fix: e.fix),
                                         left: plan.steps.enumerated().filter { $0.offset >= done.count && $0.offset != i }.map(\.element), error: failure)
        }
        // Everything that may be asked is, once, before the first step: nothing then waits for an answer half way through.
        if let i = plan.steps.firstIndex(where: \.writesStore) {
            do { try vault.unlock(try storeFile(), reason: "storing the new keys") } catch { throw failure(at: i, error) }
        }
        if let i = plan.steps.firstIndex(where: { if case .listing = $0.work { true } else { false } }) {
            do { try vault.unlock(toRead: plan.known.listingSecrets, team: team) } catch { throw failure(at: i, error) }
        }
        if let i = plan.steps.firstIndex(where: \.web) {
            do { side = try await web() } catch { throw failure(at: i, error) }
        }
        for (i, step) in plan.steps.enumerated() {
            do {
                var found: [ProvisionDrift] = []
                let result = try await run(step, state: &state, web: side, drift: &found, planNotes: plan.notes)
                applied.done.append(ProvisionDone(area: step.area, subject: step.subject, result: result))
                tell("\(i + 1)/\(plan.steps.count) \(result)")
                for d in found where !plan.drift.contains(d) && !applied.drift.contains(d) {
                    applied.drift.append(d)
                    tell("drift: \(d.subject): \(d.message) — \(d.fix)")
                }
            } catch {
                throw failure(at: i, error)
            }
        }
        return applied
    }

    func bundle(_ identifier: String, _ state: inout ProvisionState) async throws -> String {
        if let known = state.bundles[identifier] { return known }
        guard let found = try await account.bundleID(identifier) else {
            throw XlessError(.account, "bundle ID \(identifier) is not registered", fix: "re-run `xless provision apply` (it registers it first)")
        }
        state.bundles[identifier] = found
        return found
    }

    func app(_ state: inout ProvisionState) async throws -> String {
        if let id = state.appID { return id }
        guard let bundle = inputs.appStoreBundleID, let found = try await account.findApp(bundleID: bundle) else {
            throw XlessError(.account, "the app record does not exist yet", fix: "re-run `xless provision apply` (it creates it first)")
        }
        state.appID = found.id
        return found.id
    }

    func storeFile() throws -> SecretCatalog { try vault.existing() }

    /// Runs one step; drift it finds (the listing planned again while pushing) goes into `drift`.
    func run(_ step: ProvisionStep, state: inout ProvisionState, web: ProvisionWebSide?, drift: inout [ProvisionDrift],
             planNotes: [String] = []) async throws -> String {
        switch step.work {
        case .bundleID(let id):
            state.bundles[id] = try await account.register(bundleID: id)
            return "registered bundle ID \(id)"

        case .capability(let id, let request):
            try await account.enable(request, on: try await bundle(id, &state), identifier: id)
            return "enabled \(request.type.rawValue) on \(id)"

        case .linked(let kind, let identifier, let bundles):
            guard let web else { throw XlessError(.account, "the Apple ID web session is not open", fix: "this is a bug in xless; please report it") }
            let portal = web.portal(kind)
            var did: [String] = []
            let item: PortalIdentifier
            if let found = try await portal.list().first(where: { $0.identifier == identifier }) { item = found } else {
                item = try await portal.create(identifier: identifier, name: PortalName.from(identifier: identifier)).item
                did.append("created \(kind.noun) \(identifier)")
            }
            for b in bundles {
                let target = try await portal.bundle(b)
                let state = try await portal.linked(of: target)
                if kind == .cloudContainer, !state.present {
                    throw XlessError(.account, "\(b) does not have the iCloud capability, so \(identifier) cannot be assigned to it",
                                     fix: "enable it with `xless bundle-ids capabilities \(b) enable ICLOUD`")
                }
                guard !state.enabled || !state.ids.contains(item.id) else { continue }
                _ = try await portal.setLinked(state.ids.contains(item.id) ? state.ids : state.ids + [item.id], enabled: true, on: target)
                did.append("assigned \(identifier) to \(b)")
            }
            return did.isEmpty ? "\(kind.noun) \(identifier) was in place already" : did.joined(separator: ", ")

        case .certificate(let kind, let source):
            let (id, line) = try await certificate(kind, source)
            state.certificates[kind] = id
            return line

        case .apnsKey:
            guard let web else { throw XlessError(.account, "the Apple ID web session is not open", fix: "this is a bug in xless; please report it") }
            if let key = try await ProvisionPlanner.apnsKeysAtApple(web)?.first { tell("note: " + ProvisionPlanner.apnsElsewhere(key)); return "APNs key \(key.id) exists" }
            let file = try storeFile()
            try vault.unlock(file, reason: "storing the new APNs key")
            let keys = AuthKeyStore(store: vault.store, catalogID: file.id)
            let created = try await AuthKeyCreation(web: web.authKeys, vault: keys, say: tell).run(name: nil, services: [.apns], bundleIDs: [], team: team, now: now)
            return "created APNs key \(created.keyID), stored as \(created.entry)"

        case .profile(let t):
            let name = t.profileName
            let bundle = try await bundle(t.bundleID, &state)
            if let existing = try await account.profiles(named: name, type: t.profileType).first { return "profile \(name) exists (\(existing.id))" }
            guard let cert = state.certificates[t.signingKind] else {
                throw XlessError(.account, "no \(t.signingKind.certificateType.displayName) certificate to put in \(name)", fix: "re-run `xless provision apply` (it creates the certificate first)")
            }
            let created = try await account.createProfile(name: name, type: t.profileType, bundleResourceID: bundle, bundleID: t.bundleID, certificateID: cert)
            return "created profile \(name) (\(created.id))"

        case .app(let request):
            let creation = AppCreation(api: account, web: {
                guard let web else { throw XlessError(.account, "the Apple ID web session is not open", fix: "this is a bug in xless; please report it") }
                return web.apps
            }, confirm: { _, _ in true }, say: tell)
            guard let made = try await creation.run(request), let app = made.created.first ?? made.existing.first else {
                throw XlessError(.account, "the app record for \(request.bundleID) was not created", fix: "re-run `xless provision apply`")
            }
            state.appID = app.id
            return made.created.isEmpty ? "app record \(app.id) exists for \(request.bundleID)" : "created app record \(app.id) for \(request.bundleID)"

        case .listing:
            guard let store else { return "no appstore/ to push" }
            let pushed = try await store.listing.apply(appID: try await app(&state))
            drift += pushed.held.map(ProvisionPlanner.listingDrift)
            // The plan's own notes were shown with it; what planning the listing again found is said now.
            for note in pushed.notes where !planNotes.contains(note) { tell("note: \(note)") }
            return "pushed the App Store listing (\(pushed.sent) change\(pushed.sent == 1 ? "" : "s"))"

        case .privacy(let want):
            guard let web else { throw XlessError(.account, "the Apple ID web session is not open", fix: "this is a bug in xless; please report it") }
            let appID = try await app(&state)
            let changes = ProvisionPlanner.privacyChanges(try await web.privacy.plan(want, app: appID, appName: inputs.appStoreBundleID ?? appID)).send
            for change in changes { try await web.privacy.apply(change, app: appID) }
            return changes.isEmpty ? "App Privacy answers were in place already" : "sent the App Privacy answers (\(changes.count) change\(changes.count == 1 ? "" : "s"))"

        case .betaGroup(let name, let external):
            let appID = try await app(&state)
            if try await account.betaGroups(app: appID).contains(where: { $0.name == name }) { return "TestFlight group \(name) exists" }
            try await account.createBetaGroup(name: name, app: appID, external: external)
            return "created \(external ? "external" : "internal") TestFlight group \(name)"
        }
    }

    /// Creates the certificate of `kind` for the key `source` names: generated and stored first (`CertificateCreation`),
    /// the store's own (recorded with it once made), or the environment's. Returns its ID and what was done.
    func certificate(_ kind: CertificateKind, _ source: ProvisionStep.KeySource) async throws -> (String, String) {
        let type = kind.certificateType
        switch source {
        case .generate(let entry):
            let file = try storeFile()
            try CertificateKeyStore.precheck(file, name: entry, base: kind.secretName, team: team, stage: .account,
                                             keepBoth: "remove it, or import the key that goes with the certificate you use")
            let created = try await CertificateCreation(api: account, say: tell).run(type: type, relatedID: nil, entry: entry, team: team, keys: {
                try vault.unlock(file, reason: "storing the new certificate's private key")
                return CertificateKeyStore(store: vault.store, catalogID: file.id)
            }, now: now)
            return (created.certificate.id, "created \(type.displayName) certificate \(created.certificate.id), its key stored as \(entry)")
        case .stored(let entry):
            let file = try storeFile()
            guard let stored = file.entry(named: entry) else {
                throw XlessError(.account, "the secret store no longer has \(entry)", fix: "re-run `xless provision apply`")
            }
            // The certificate's ID is recorded with the key once it is made: a store this xless cannot write (or a
            // credential helper that cannot store) refuses here, before the request.
            try vault.unlock(file, reason: "recording the new certificate with \(entry)")
            let secret = try vault.open(stored, in: file, reason: "a certificate for \(entry)")
            defer { secret.wipe() }
            let cert = try await create(type, key: try SigningKey(pem: secret.utf8String()))
            let keys = CertificateKeyStore(store: vault.store, catalogID: file.id)
            let facts = cert.der.flatMap { CertificateFacts(der: $0) }
            do {
                try keys.record(name: entry, secret: secret, certificateID: cert.id, expires: facts?.expires ?? cert.expires, team: facts?.teamID ?? team)
            } catch {
                tell("warning: certificate \(cert.id) was created for \(entry), but its ID could not be recorded with it (\(XlessError.wrapping(error, stage: .account).cause)); the sign stage and the next plan still find it by its public key")
            }
            return (cert.id, "created \(type.displayName) certificate \(cert.id) for the key stored as \(entry)")
        case .environment(let name):
            guard let pem = try vault.environmentKey(name) else {
                throw XlessError(.account, "\(name) is no longer set", fix: "set it again (or \(name)_FILE), then re-run")
            }
            let cert = try await create(type, key: try SigningKey(pem: pem))
            return (cert.id, "created \(type.displayName) certificate \(cert.id) for the key in \(name)")
        }
    }

    /// One create request for an existing key, with the refusals `xless certs create` gives.
    func create(_ type: CertificateType, key: SigningKey) async throws -> ASCCertificate {
        let creation = CertificateCreation(api: account, say: tell)
        try await creation.precheck(type)
        // The key may have had certificates before (gone, or expired): only one made by this request counts.
        let before = try await creation.existingIDs()
        do {
            return try await account.create(type: type, csrPEM: try key.csrPEM(commonName: "xless"), relatedID: nil)
        } catch {
            guard ASCCertificates.isAmbiguous(error) else { throw creation.refused(type, error) }
            if let made = await creation.made(type, for: KeyMatch.publicKey(privateKeyPEM: key.pem), after: error, excluding: before) { return made }
            throw creation.ambiguous(type, error)
        }
    }
}
