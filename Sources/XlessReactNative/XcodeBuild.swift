import Foundation
import XlessCore
import XlessTauri
import XlessXcode

/// The React Native build on a Mac: `xcodebuild` of the workspace with the Xcode that is installed, where Linux has Swift Build. It
/// runs in xless's sandbox (docs/security.md, "An overlay's build on a Mac"), in which there can be no other: SwiftPM's, the Swift
/// compiler's and the script phases' own are off. Asset catalogs and storyboards are compiled by xless, as on Linux.
public struct XcodeBuild: Sendable {
    let sdk: DarwinSDK
    /// Of the Xcode, for the stand-ins for actool and ibtool.
    let meta: ToolchainMeta
    /// The xless that they are.
    let executable: URL

    public init(sdk: DarwinSDK, meta: ToolchainMeta, executable: URL = (Bundle.main.executableURL ?? URL(fileURLWithPath: CommandLine.arguments[0])).resolvingSymlinksInPath()) {
        self.sdk = sdk; self.meta = meta; self.executable = executable
    }

    /// What builds the app, for `ReactNativeBuilder.toolchainIdentity`.
    var identity: String { "Xcode \(meta.xcodeVersion) (\(meta.xcodeBuild)) at \(sdk.bundle.path)" }

    // MARK: - Tools

    /// Writes the programs that the build finds before those on PATH: `swift` (`RustApple.writeSwiftWrapper`), and `xcrun`, for the pods'
    /// phases that ask it for actool or ibtool.
    func writeTools(work: URL) throws {
        let directory = RustApple.wrapperDirectory(workRoot: work), metaFile = directory.appendingPathComponent("toolchain-meta.json")
        try RustApple.writeSwiftWrapper(sdk: sdk, workRoot: work)
        try meta.write(to: metaFile)
        for tool in ["actool", "ibtool"] {
            try ExecutableFile.write("""
                #!/bin/sh
                # Generated by xless: Xcode's own \(tool) does not work in the sandbox.
                XLESS_TOOLCHAIN_META=\(quote(metaFile.path)) exec \(quote(executable.path)) shim \(tool) "$@"

                """, to: directory.appendingPathComponent(tool), stage: .build)
        }
        try ExecutableFile.write("""
            #!/bin/sh
            # Generated by xless: xcrun, but that actool and ibtool are xless's.
            case "$1" in
            actool|ibtool) tool=$1; shift; exec \(quote(directory.path))/"$tool" "$@" ;;
            --find|-find|-f) case "$2" in actool|ibtool) echo \(quote(directory.path))/"$2"; exit ;; esac ;;
            esac
            exec /usr/bin/xcrun "$@"

            """, to: directory.appendingPathComponent("xcrun"), stage: .build)
    }

    private func quote(_ s: String) -> String { "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'" }

    // MARK: - Settings

    /// An `-xcconfig` (it comes before every other setting) that gives each target of `settings` its own values, and leaves those of
    /// the others: Xcode's evaluation picks the one for the target that it evaluates.
    static func configuration(_ settings: [(project: String, target: String, values: [String: String])]) throws -> String {
        var lines: [String] = ["// Generated by xless.", "EXCLUDED_ARCHS[sdk=iphonesimulator*] = x86_64"], seen: Set<String> = []
        var names: Set<String> = []
        for (project, target, values) in settings {
            let own = try "\(identifier(project))__\(identifier(target))"
            guard seen.insert(own).inserted else {
                throw XlessError(.build, "two targets have names that Xcode's settings cannot tell apart: \(target) is one of them", fix: "rename it, or build in Docker: add --docker")
            }
            for (name, value) in values.sorted(by: { $0.key < $1.key }) {
                guard !value.contains(where: { $0.isNewline }), !value.contains("//"), !value.contains("$") else {
                    throw XlessError(.build, "\(name) of \(target) is \(value), which an xcconfig cannot hold", fix: "build in Docker: add --docker")
                }
                lines.append("XLESS_\(name)__\(own) = \(value)")
                names.insert(name)
            }
        }
        for name in names.sorted() {
            lines.append("\(name) = $(XLESS_\(name)__$(PROJECT_NAME:c99extidentifier)__$(TARGET_NAME:c99extidentifier):default=$(inherited))")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// `name:c99extidentifier`, as Xcode makes it of ASCII.
    private static func identifier(_ name: String) throws -> String {
        guard name.allSatisfy(\.isASCII) else {
            throw XlessError(.build, "the target or project \(name) has a name that is not ASCII, which xless does not build with xcodebuild", fix: "rename it, or build in Docker: add --docker")
        }
        let out = name.map { $0.isLetter || $0.isNumber ? $0 : "_" }
        return String(out.first?.isNumber == true ? ["_"] + out.dropFirst() : out)
    }

    /// Of the command line, so for every target.
    static func arguments(workspace: URL, scheme: String, configuration: String, destination: BuildRequest.Destination, derivedData: URL, xcconfig: URL,
                          tools: URL, settings: [String: String]) -> [String] {
        let own = ["OTHER_SWIFT_FLAGS": "$(inherited) -disable-sandbox", "ENABLE_USER_SCRIPT_SANDBOXING": "NO",
                   "ASSETCATALOG_EXEC": tools.appendingPathComponent("actool").path, "IBC_EXEC": tools.appendingPathComponent("ibtool").path]
        return ["-workspace", workspace.path, "-scheme", scheme, "-configuration", configuration,
                "-destination", destination == .iphoneos ? "generic/platform=iOS" : "generic/platform=iOS Simulator",
                "-derivedDataPath", derivedData.path, "-xcconfig", xcconfig.path,
                "-IDEPackageSupportDisableManifestSandbox=1", "-IDEPackageSupportDisablePluginExecutionSandbox=1", "-skipMacroValidation", "-skipPackagePluginValidation", "build"]
            + settings.merging(own) { $1 }.sorted { $0.key < $1.key }.map { "\($0.key)=\($0.value)" }
    }

    /// Builds; `log` is what it printed. A failure names the errors in it.
    func run(_ arguments: [String], log: URL, env: [String: String?], baseEnvironment: [String: String]) throws {
        let program = sdk.bundle.appendingPathComponent("Developer/usr/bin/xcodebuild").path
        do {
            try Shell.run("/bin/sh", ["-c", "log=$1; shift; exec \"$@\" > \"$log\" 2>&1", "sh", log.path, program] + arguments, env: env, baseEnvironment: baseEnvironment, stage: .build)
        } catch is XlessError {
            let lines = ((try? Data(contentsOf: log)).map { String(decoding: $0, as: UTF8.self) } ?? "").split(separator: "\n").map(String.init)
            let errors = Self.errors(in: lines)
            for line in errors.isEmpty ? lines.suffix(20) : errors.prefix(20) { FileHandle.standardError.write(Data("  | \(line)\n".utf8)) }
            throw XlessError(.build, "xcodebuild failed: \(errors.first ?? lines.last ?? "it printed nothing")", fix: "see the errors above and \(log.path)")
        }
    }

    /// Those that say what is wrong, once each.
    static func errors(in lines: [String]) -> [String] {
        var seen: Set<String> = []
        return lines.filter { ($0.hasPrefix("error: ") || $0.contains(": error: ")) && seen.insert($0).inserted }
    }
}
